//! Fixed source and documentation for the bounded native tray template.

use super::{TemplateContext, json_string, quoted, windows_path};

const TRAY: &str = r#"{"items":[{"id":"template.tray.complete","label":"Complete tray template session","enabled":true}]}"#;

pub(super) fn main_source(display_label: &str) -> String {
    let document = document_json(display_label);
    format!(
        "{MAIN_PREFIX}{}{MAIN_MIDDLE}{}{MAIN_SUFFIX}",
        quoted(&document),
        quoted(TRAY),
    )
}

