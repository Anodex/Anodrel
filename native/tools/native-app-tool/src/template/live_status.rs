use super::{TemplateContext, json_string, quoted, windows_path};

pub(super) fn main_source(display_label: &str) -> String {
    let initial = document(
        display_label,
        "Ready to publish a visible result.",
        "polite",
        "template.status.polite",
        "Publish polite result",
    );
    let polite = document(
        display_label,
        "Verification is complete.",
        "polite",
        "template.status.assertive",
        "Publish assertive result",
    );
    let assertive = document(
        display_label,
        "Verification succeeded.",
        "assertive",
        "template.status.complete",
        "Complete status session",
    );
    format!(
        "{MAIN_PREFIX}{};\nconst POLITE_DOCUMENT: &str = {};\nconst ASSERTIVE_DOCUMENT: &str = {}{MAIN_SUFFIX}",
        quoted(&initial),
        quoted(&polite),
        quoted(&assertive),
    )
}

