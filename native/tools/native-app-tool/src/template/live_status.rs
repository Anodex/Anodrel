#[cfg(test)]
mod tests {
    use super::document;

    #[test]
    fn fixed_live_status_documents_use_the_strict_v3_contract() {
        let document = document(
            "Generated Live Status Template",
            "Ready",
            "polite",
            "template.status.polite",
            "Publish polite result",
        );
        let decoded = anodrel_ui_document::decode_v3(&document)
            .expect("fixed live-status document is strict v3");
        assert_eq!(decoded.root().id().as_str(), "template.status.root");
        assert_eq!(decoded.status().map(|status| status.value()), Some("Ready"));
    }
}
