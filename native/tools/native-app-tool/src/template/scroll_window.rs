const MAIN_PREFIX: &str = r##"#![deny(unsafe_op_in_unsafe_fn)]

//! A constrained native Anodrel scroll-window template.
//!
//! The host supplies one private bootstrap invitation on standard input. This
//! program opens only that invited Windows pipe, uses the explicit version-2
//! secondary-document client methods, and never selects host capabilities or
//! observes native scroll state.

use std::{io, process::ExitCode, thread};

use anodrel_client::{Client, InteractivePollSchedule};
use anodrel_ui_client::{SessionWindowId, UiSession};
use anodrel_windows_client::WindowsClientStream;

const PRIMARY_OPEN_ACTION: &str = "template.scroll.open";
const SECONDARY_REVEAL_ACTION: &str = "template.scroll.reveal";
const SECONDARY_COMPLETE_ACTION: &str = "template.scroll.complete";
const SECONDARY_TITLE: &str = "Template scrollable secondary";
const PRIMARY_DOCUMENT: &str = "##;

const MAIN_SUFFIX: &str = r##"

type NativeUiClient = Client<WindowsClientStream>;

#[derive(Clone, Copy)]
enum Stage {
    Completed,
    BootstrapUnreadable,
    EndpointUnavailable,
    AuthenticationRejected,
    DocumentRejected,
    WindowOpenRejected,
    WindowUpdateRejected,
    EventReadFailed,
    ActionNotObserved,
    WindowCloseRejected,
    CloseRejected,
}

impl Stage {
    const fn code(self) -> u8 {
        match self {
            Self::Completed => 0,
            Self::BootstrapUnreadable => 101,
            Self::EndpointUnavailable => 102,
            Self::AuthenticationRejected => 103,
            Self::DocumentRejected => 104,
            Self::WindowOpenRejected => 105,
            Self::WindowUpdateRejected => 106,
            Self::EventReadFailed => 107,
            Self::ActionNotObserved => 108,
            Self::WindowCloseRejected => 109,
            Self::CloseRejected => 110,
        }
    }
}

fn main() -> ExitCode {
    ExitCode::from(run().code())
}

fn run() -> Stage {
    let Ok(invitation) = NativeUiClient::read_invitation(&mut io::stdin()) else {
        return Stage::BootstrapUnreadable;
    };
    let Ok(stream) = WindowsClientStream::connect(&invitation) else {
        return Stage::EndpointUnavailable;
    };
    let Ok(client) = NativeUiClient::authenticate(stream, invitation) else {
        return Stage::AuthenticationRejected;
    };
    let mut session = UiSession::new(client);
    let Ok(primary_revision) = session.replace_document_v1(PRIMARY_DOCUMENT) else {
        return Stage::DocumentRejected;
    };
    if primary_revision.value() != 1 {
        return Stage::DocumentRejected;
    }
    if let Err(stage) = wait_for_action(
        &mut session,
        SessionWindowId::Main,
        PRIMARY_OPEN_ACTION,
        primary_revision.value(),
    ) {
        return stage;
    }
    let Ok(secondary) = session.open_window_v2(SECONDARY_TITLE, SECONDARY_WAITING_DOCUMENT) else {
        return Stage::WindowOpenRejected;
    };
    if let Err(stage) = wait_for_action(
        &mut session,
        SessionWindowId::Secondary(secondary),
        SECONDARY_REVEAL_ACTION,
        1,
    ) {
        return stage;
    }
    let Ok(secondary_revision) =
        session.replace_window_document_v2(secondary, SECONDARY_COMPLETE_DOCUMENT)
    else {
        return Stage::WindowUpdateRejected;
    };
    if secondary_revision.value() != 2 {
        return Stage::WindowUpdateRejected;
    }
    if let Err(stage) = wait_for_action(
        &mut session,
        SessionWindowId::Secondary(secondary),
        SECONDARY_COMPLETE_ACTION,
        secondary_revision.value(),
    ) {
        return stage;
    }
    if session.close_window(secondary).is_err() {
        return Stage::WindowCloseRejected;
    }
    if session.close().is_err() {
        return Stage::CloseRejected;
    }
    Stage::Completed
}

fn wait_for_action(
    session: &mut UiSession<WindowsClientStream>,
    expected_window: SessionWindowId,
    expected_action: &str,
    expected_revision: u64,
) -> Result<(), Stage> {
    for interval in InteractivePollSchedule::new() {
        let batch = session.read_window_actions().map_err(|_| Stage::EventReadFailed)?;
        if batch.dropped() != 0 || batch.discarded() != 0 {
            return Err(Stage::EventReadFailed);
        }
        match batch.actions() {
            [] => thread::sleep(interval),
            [action]
                if action.window() == expected_window
                    && action.action().action() == expected_action
                    && action.action().revision().value() == expected_revision => return Ok(()),
            _ => return Err(Stage::EventReadFailed),
        }
    }
    Err(Stage::ActionNotObserved)
}
"##;

#[cfg(test)]
mod tests {
    use super::{primary_document, secondary_document};

    #[test]
    fn fixed_walkthrough_documents_keep_v1_primary_and_v2_secondary_boundaries() {
        let primary = primary_document("Generated Scroll Window Template");
        anodrel_ui_document::decode(&primary).expect("fixed primary document is strict v1");

        for (name, document) in [
            (
                "secondary waiting",
                secondary_document(
                    "SCROLLABLE SECONDARY VIEW",
                    "Scroll locally.",
                    "template.scroll.reveal",
                    "Reveal updated scroll document",
                ),
            ),
            (
                "secondary complete",
                secondary_document(
                    "SECONDARY DOCUMENT UPDATED",
                    "Scroll locally again.",
                    "template.scroll.complete",
                    "Close secondary and finish",
                ),
            ),
        ] {
            let decoded = anodrel_ui_document::decode_v2(&document)
                .unwrap_or_else(|error| panic!("{name} generated document is invalid: {error}"));
            assert_eq!(decoded.root().id().as_str(), "template.scroll.viewport");
            assert!(matches!(decoded.root(), anodrel_ui::UiNode::Scroll(_)));
        }
    }
}
