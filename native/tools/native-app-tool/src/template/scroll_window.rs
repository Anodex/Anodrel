const CHECKPOINT_COUNT: usize = 30;

pub(super) fn main_source(display_label: &str) -> String {
    let primary = primary_document(display_label);
    let secondary_waiting = secondary_document(
        "SCROLLABLE SECONDARY VIEW",
        "Scroll locally to reach the action below. The host retains this view's position.",
        "template.scroll.reveal",
        "Reveal updated scroll document",
    );
    let secondary_complete = secondary_document(
        "SECONDARY DOCUMENT UPDATED",
        "This is revision two of the same scrollable secondary view. Scroll to finish.",
        "template.scroll.complete",
        "Close secondary and finish",
    );
    format!(
        "{MAIN_PREFIX}{};\nconst SECONDARY_WAITING_DOCUMENT: &str = {};\nconst SECONDARY_COMPLETE_DOCUMENT: &str = {};{MAIN_SUFFIX}",
        quoted(&primary),
        quoted(&secondary_waiting),
        quoted(&secondary_complete),
    )
}

