//! Fixed generated source for the explicit native multi-window template.

use super::{TemplateContext, json_string, quoted, windows_path};

pub(super) fn main_source(display_label: &str) -> String {
    let primary = primary_document(display_label);
    let secondary_waiting = secondary_waiting_document();
    let secondary_complete = secondary_complete_document();
    format!(
        "{MAIN_PREFIX}{};\nconst SECONDARY_WAITING_DOCUMENT: &str = {};\nconst SECONDARY_COMPLETE_DOCUMENT: &str = {}{MAIN_SUFFIX}",
        quoted(&primary),
        quoted(&secondary_waiting),
        quoted(&secondary_complete),
    )
}

