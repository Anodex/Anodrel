//! Fixed source and documentation for the bounded native-menu template.

use super::{TemplateContext, json_string, quoted, windows_path};

const MENU: &str = r#"{"menus":[{"label":"File","items":[{"id":"template.menu.complete","label":"Complete menu template session","enabled":true,"shortcut":"Ctrl+Shift+M"}]}]}"#;

pub(super) fn main_source(display_label: &str) -> String {
    let document = document_json(display_label);
    format!(
        "{MAIN_PREFIX}{}{MAIN_MIDDLE}{}{MAIN_SUFFIX}",
        quoted(&document),
        quoted(MENU),
    )
}

