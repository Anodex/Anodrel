fn document_json(display_label: &str) -> String {
    let label = json_string(display_label);
    format!(
        "{{\"format\":\"anodrel.ui.document.v1\",\"root\":{{\"id\":\"template.menu.root\",\"kind\":\"stack\",\"axis\":\"vertical\",\"padding\":{{\"left\":56,\"top\":56,\"right\":56,\"bottom\":56}},\"gap\":16,\"surfaceTone\":\"plain\",\"children\":[{{\"id\":\"template.menu.eyebrow\",\"kind\":\"text\",\"value\":\"ANODREL NATIVE MENU TEMPLATE\",\"fontSize\":14,\"tone\":\"accent\"}},{{\"id\":\"template.menu.title\",\"kind\":\"text\",\"value\":{label},\"fontSize\":28,\"tone\":\"primary\"}},{{\"id\":\"template.menu.detail\",\"kind\":\"text\",\"value\":\"Use File > Complete menu template session or Ctrl+Shift+M to return one typed native menu action.\",\"fontSize\":16,\"tone\":\"secondary\"}}]}}}}"
    )
}

const MAIN_PREFIX: &str = r##"#![deny(unsafe_op_in_unsafe_fn)]

//! A constrained native Anodrel menu template.
//!
//! The host supplies one private bootstrap invitation on standard input. This
//! program opens only that invited Windows pipe, uses the typed menu surface,
//! and never selects host capabilities or native window resources.

use std::{io, process::ExitCode, thread};

use anodrel_client::{Client, InteractivePollSchedule};
use anodrel_ui_client::{UiEvent, UiSession};
use anodrel_windows_client::WindowsClientStream;

const COMPLETE_ACTION: &str = "template.menu.complete";
const DOCUMENT: &str = "##;

const MAIN_MIDDLE: &str = r##";
const MENU: &str = "##;

const MAIN_SUFFIX: &str = r##";

type NativeUiClient = Client<WindowsClientStream>;

#[derive(Clone, Copy)]
enum Stage {
    Completed,
    BootstrapUnreadable,
    EndpointUnavailable,
    AuthenticationRejected,
    DocumentRejected,
    MenuRejected,
    EventReadFailed,
    ActionNotObserved,
    CloseRejected,
}

impl Stage {
    const fn code(self) -> u8 {
        match self {
            Self::Completed => 0,
            Self::BootstrapUnreadable => 61,
            Self::EndpointUnavailable => 62,
            Self::AuthenticationRejected => 63,
            Self::DocumentRejected => 64,
            Self::MenuRejected => 65,
            Self::EventReadFailed => 66,
            Self::ActionNotObserved => 67,
            Self::CloseRejected => 68,
        }
    }
}

fn main() -> ExitCode {
    ExitCode::from(run().code())
}

fn run() -> Stage {
    let Ok(invitation) = NativeUiClient::read_invitation(&mut io::stdin()) else {
        return Stage::BootstrapUnreadable;
    };
    let Ok(stream) = WindowsClientStream::connect(&invitation) else {
        return Stage::EndpointUnavailable;
    };
    let Ok(client) = NativeUiClient::authenticate(stream, invitation) else {
        return Stage::AuthenticationRejected;
    };
    let mut session = UiSession::new(client);
    let Ok(document_revision) = session.replace_document_v1(DOCUMENT) else {
        return Stage::DocumentRejected;
    };
    if document_revision.value() != 1 {
        return Stage::DocumentRejected;
    }
    let Ok(menu_revision) = session.replace_menu_v1(MENU) else {
        return Stage::MenuRejected;
    };
    if menu_revision.value() != 1 {
        return Stage::MenuRejected;
    }
    for interval in InteractivePollSchedule::new() {
        let Ok(batch) = session.read_events() else {
            return Stage::EventReadFailed;
        };
        if batch.dropped() != 0 || batch.discarded() != 0 {
            return Stage::EventReadFailed;
        }
        match batch.events() {
            [] => thread::sleep(interval),
            [UiEvent::MenuAction(action)]
                if action.action() == COMPLETE_ACTION && action.revision().value() == 1 =>
            {
                return if session.close().is_ok() {
                    Stage::Completed
                } else {
                    Stage::CloseRejected
                };
            }
            _ => return Stage::EventReadFailed,
        }
    }
    Stage::ActionNotObserved
}
"##;

