fn bytes_text() -> String {
    BINARY_BYTES
        .iter()
        .map(|byte| format!("0x{byte:02X}"))
        .collect::<Vec<_>>()
        .join(", ")
}

const MAIN_PREFIX: &str = r##"#![deny(unsafe_op_in_unsafe_fn)]

//! A constrained native Anodrel retained binary file-write template.
//!
//! The host supplies one private bootstrap invitation on standard input. This
//! program opens only that invited Windows pipe and writes only through one
//! opaque output reference returned from the host-owned save picker.

use std::process::ExitCode;

use anodrel_windows_ui_sdk::{
    FileBinaryData, FileDialogFilter, SaveSelectionResult, WindowsUiConnectionError,
    WindowsUiSession,
};

const DOCUMENT: &str = "##;

const MAIN_DOCUMENT_TO_DATA: &str = r##";
const BINARY_BASE64URL: &str = "##;

const MAIN_DATA_TO_BYTES: &str = r##";
const BINARY_BYTES: &[u8] = &["##;

const MAIN_SUFFIX: &str = r##"];

#[derive(Clone, Copy)]
enum Stage {
    Completed,
    BootstrapUnreadable,
    EndpointUnavailable,
    AuthenticationRejected,
    DocumentRejected,
    FilterRejected,
    BinaryDataRejected,
    SelectionRejected,
    WriteRejected,
    CloseRejected,
}

impl Stage {
    const fn code(self) -> u8 {
        match self {
            Self::Completed => 0,
            Self::BootstrapUnreadable => 111,
            Self::EndpointUnavailable => 112,
            Self::AuthenticationRejected => 113,
            Self::DocumentRejected => 114,
            Self::FilterRejected => 115,
            Self::BinaryDataRejected => 116,
            Self::SelectionRejected => 117,
            Self::WriteRejected => 118,
            Self::CloseRejected => 119,
        }
    }
}

fn main() -> ExitCode {
    ExitCode::from(run().code())
}

fn run() -> Stage {
    let mut session = match WindowsUiSession::connect_from_stdin() {
        Ok(session) => session,
        Err(WindowsUiConnectionError::BootstrapUnavailable) => return Stage::BootstrapUnreadable,
        Err(WindowsUiConnectionError::InvitedEndpointUnavailable) => {
            return Stage::EndpointUnavailable;
        }
        Err(WindowsUiConnectionError::AuthenticationUnavailable) => {
            return Stage::AuthenticationRejected;
        }
    };
    let Ok(document_revision) = session.replace_document_v1(DOCUMENT) else {
        return Stage::DocumentRejected;
    };
    if document_revision.value() != 1 {
        return Stage::DocumentRejected;
    }
    let Ok(filter) = FileDialogFilter::new("Binary files", vec!["bin".to_owned()]) else {
        return Stage::FilterRejected;
    };
    let Ok(data) = FileBinaryData::decode_base64url(BINARY_BASE64URL) else {
        return Stage::BinaryDataRejected;
    };
    if data.as_bytes() != BINARY_BYTES {
        return Stage::BinaryDataRejected;
    }
    match session.select_save_file_v2(&[filter]) {
        Ok(SaveSelectionResult::Selected(selection)) => {
            if session
                .write_selected_binary(selection.reference(), &data)
                .is_err()
            {
                return Stage::WriteRejected;
            }
        }
        Ok(SaveSelectionResult::Cancelled) => {}
        Err(_) => return Stage::SelectionRejected,
    }
    if session.close().is_ok() {
        Stage::Completed
    } else {
        Stage::CloseRejected
    }
}
"##;

#[cfg(test)]
mod tests {
    use super::{BINARY_BASE64URL, BINARY_BYTES, document_json, main_source};

    #[test]
    fn fixed_source_uses_one_canonical_retained_binary_output() {
        assert!(anodrel_ui_document::decode(&document_json("Binary Write App")).is_ok());
        let source = main_source("Binary Write App");
        assert!(source.contains("FileBinaryData::decode_base64url(BINARY_BASE64URL)"));
        assert!(source.contains("write_selected_binary(selection.reference(), &data)"));
        assert!(source.contains("SaveSelectionResult::Cancelled"));
        assert!(!source.contains("std::fs"));
        assert!(!source.contains("read_actions"));
        assert!(!source.contains("write_selected_text"));
        assert_eq!(
            anodrel_file_access::FileBinaryData::decode_base64url(BINARY_BASE64URL)
                .expect("fixed value is canonical")
                .as_bytes(),
            BINARY_BYTES
        );
    }
}
