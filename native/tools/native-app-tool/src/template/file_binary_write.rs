//! Fixed source and documentation for the retained native binary-write template.

use super::{TemplateContext, json_string, quoted, windows_path};

const BINARY_BASE64URL: &str = "QW5vZHJlbAD_";
const BINARY_BYTES: &[u8] = &[0x41, 0x6E, 0x6F, 0x64, 0x72, 0x65, 0x6C, 0x00, 0xFF];

pub(super) fn main_source(display_label: &str) -> String {
    let document = document_json(display_label);
    format!(
        "{MAIN_PREFIX}{}{MAIN_DOCUMENT_TO_DATA}{}{MAIN_DATA_TO_BYTES}{}{MAIN_SUFFIX}",
        quoted(&document),
        quoted(BINARY_BASE64URL),
        bytes_text(),
    )
}

